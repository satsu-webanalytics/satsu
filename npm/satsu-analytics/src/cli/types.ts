import { existsSync } from "node:fs";
import { readFile, writeFile } from "node:fs/promises";
import { join } from "node:path";
import * as p from "@clack/prompts";
import { authed } from "./api";
import { CliError, credentialsPath, readCredentials } from "./auth";
import { readEnvValue } from "./codemod";
import { detectFramework } from "./detect";

export const TYPES_FILE = "satsu-events.d.ts";

const IDENT = /^[A-Za-z_$][A-Za-z0-9_$]*$/;

/** Custom-event names from a goals response; path goals have no event name. */
export function eventNames(goals: unknown): string[] {
  const list: unknown[] = Array.isArray(goals) ? goals : Array.isArray((goals as any)?.goals) ? (goals as any).goals : [];
  const names = list
    .filter((g: any) => g?.type === "custom_event" && typeof g.matcher === "string" && g.matcher.trim() !== "")
    .map((g: any) => g.matcher as string);
  return [...new Set(names)].sort();
}

/** Declaration-merging file for `Events`; props are free-form because goals don't declare them. */
export function renderTypes(names: string[]): string {
  const props = "Record<string, string | number | boolean> | undefined";
  const body = names.map((n) => `    ${IDENT.test(n) ? n : JSON.stringify(n)}: ${props};`).join("\n");
  return `// Generated by \`npx satsu-analytics types\` from your Satsu goals. Do not edit.
import "satsu-analytics";

declare module "satsu-analytics" {
  interface Events {
${body}
  }
}
`;
}

async function projectSite(cwd: string): Promise<string | null> {
  const fw = detectFramework(cwd);
  if (!fw.supported) return null;
  const path = join(cwd, fw.envFile);
  const text = existsSync(path) ? await readFile(path, "utf8") : null;
  return readEnvValue(text, fw.envVar) ?? null;
}

/** `types [--site <id>]`: writes satsu-events.d.ts from the site's custom-event goals. */
export async function types(
  args: string[],
  cwd = process.cwd(),
  env: NodeJS.ProcessEnv = process.env,
): Promise<boolean> {
  p.intro("satsu-analytics types");
  try {
    const i = args.indexOf("--site");
    const site = (i >= 0 ? args[i + 1] : undefined) ?? (await projectSite(cwd));
    if (!site) throw new CliError("No site found. Pass --site <id> or run init first.");
    const creds = await readCredentials(credentialsPath(env));
    if (!creds) throw new CliError("You are not signed in. Run `npx satsu-analytics login`.");
    const goals = await authed(creds.apiUrl, creds.key, "GET", `/v1/sites/${encodeURIComponent(site)}/goals`);
    const names = eventNames(goals);
    await writeFile(join(cwd, TYPES_FILE), renderTypes(names));
    p.outro(`Wrote ${TYPES_FILE} with ${names.length} custom event${names.length === 1 ? "" : "s"}.`);
    return true;
  } catch (e) {
    if (e instanceof CliError) {
      p.outro(e.message);
      return false;
    }
    throw e;
  }
}
